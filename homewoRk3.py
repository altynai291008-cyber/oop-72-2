while True:
    слово = input("Введите слово: ")

    if слово.lower() == "стоп" or слово.lower() == "exit" or слово == "":
        break

    всего = 0
    большие = 0
    маленькие = 0
    гласные = 0
    согласные = 0

    гласные_буквы = "аеёиоуыэюяaeiou"

    for буква in слово:
        if буква.isalpha():
            всего += 1

            if буква.isupper():
                большие += 1
            if буква.islower():
                маленькие += 1

            if буква.lower() in гласные_буквы:
                гласные += 1
            else:
                согласные += 1

    print(f"Количество букв: {всего}")
    print(f"Заглавных букв: {большие}")
    print(f"Строчных букв: {маленькие}")
    print(f"Гласных букв: {гласные}")
    print(f"Согласных букв: {согласные}")

    if всего > 0:
        проц_гласные = гласные / всего * 100
        проц_согласные = согласные / всего * 100
        print(f"Гласные/Согласные: {проц_гласные:.2f}% / {проц_согласные:.2f}%")

    print()